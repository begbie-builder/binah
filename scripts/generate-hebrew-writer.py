"""Build Hebrew-only Hanzi Writer data from font contours and authored medians.

Dev-only dependencies: fonttools, shapely >= 2.1. No build dependency.
The font boundary is flattened to <= .035 practice units, then partitioned by
the nearest median. Stroke unions reproduce the font; no bitmap silhouettes.
"""
from pathlib import Path
import json, math
from fontTools.pens.basePen import BasePen
from fontTools.svgLib.path import parse_path
from shapely import MultiPoint, Polygon, box, voronoi_polygons, union_all
from shapely.geometry import LineString

ROOT = Path(__file__).resolve().parent.parent
source = json.loads((ROOT/'scripts/data/hebrew-print-strokes.json').read_text())
raw = (ROOT/'src/letter-geometry.js').read_text().split('export const letterGeometry=')[1].strip().rstrip(';')
geometry = json.loads(raw)

class FlattenPen(BasePen):
    def __init__(self):
        super().__init__(None); self.rings=[]; self.current=[]
    def _moveTo(self,p): self.current=[p]
    def _lineTo(self,p): self.current.append(p)
    def _curveToOne(self,a,b,c):
        start=self._getCurrentPoint()
        def flatten(p0,p1,p2,p3):
            chord=LineString([p0,p3])
            from shapely import Point
            if max(chord.distance(Point(p1)),chord.distance(Point(p2)))<.035:
                self.current.append(p3); return
            mid=lambda a,b:((a[0]+b[0])/2,(a[1]+b[1])/2)
            a,b,c=mid(p0,p1),mid(p1,p2),mid(p2,p3)
            d,e=mid(a,b),mid(b,c);f=mid(d,e)
            flatten(p0,a,d,f);flatten(f,e,c,p3)
        flatten(start,a,b,c)
    def _qCurveToOne(self,a,b):
        p=self._getCurrentPoint()
        self._curveToOne((p[0]+(a[0]-p[0])*2/3,p[1]+(a[1]-p[1])*2/3),(b[0]+(a[0]-b[0])*2/3,b[1]+(a[1]-b[1])*2/3),b)
    def _closePath(self): self.rings.append(self.current); self.current=[]
    def _endPath(self): self._closePath()

def shape(path):
    pen=FlattenPen();parse_path(path,pen);result=Polygon()
    # XOR nested contours to preserve counters; Noto glyphs have no overlapping
    # filled contours. This handles Samekh/Final Mem holes without winding guesses.
    for ring in pen.rings: result=result.symmetric_difference(Polygon(ring).buffer(0))
    return result

def point(p):
    # Uniform enlargement, preserving Yod, ascenders, descenders and no mirroring.
    x,y=[50+(v-50)*1.12 for v in p]
    return [round(x*10.24,3),round(900-y*10.24,3)]

def path_for(poly):
    polys=[poly] if poly.geom_type=='Polygon' else list(poly.geoms)
    parts=[]
    for polygon in polys:
        if polygon.area<.001:continue
        for ring in [polygon.exterior,*polygon.interiors]:
            pts=[point(p) for p in ring.coords]
            parts.append('M'+'L'.join(f'{x:g},{y:g}' for x,y in pts)+'Z')
    return ''.join(parts)

out={}
for char,item in source.items():
    glyph=shape(geometry[char]['path']); samples=[];owners=[];seen=set()
    for i,median in enumerate(item['medians']):
        line=LineString(median)
        for n in range(math.ceil(line.length)+1):
            p=line.interpolate(min(n,line.length));key=(round(p.x,4),round(p.y,4))
            if key in seen:continue
            seen.add(key);samples.append(key);owners.append(i)
    cells=voronoi_polygons(MultiPoint(samples),extend_to=box(-20,-20,120,120),ordered=True)
    strokes=[]
    for i in range(len(item['medians'])):
        region=union_all([cell for cell,owner in zip(cells.geoms,owners) if owner==i]).buffer(.035)
        strokes.append(glyph.intersection(region))
    assert glyph.symmetric_difference(union_all(strokes)).area<.01, char
    assert all(s.area>1 for s in strokes),char
    out[char]={'strokes':[path_for(s) for s in strokes],
               'medians':[[point(p) for p in median] for median in item['medians']],
               'guides':[[[round(50+(v-50)*1.12,3) for v in p] for p in median] for median in item['medians']],
               'practiceMedians':item['medians'],'instructions':item['instructions']}
    print(char,len(strokes),'strokes')
(ROOT/'src/hebrew-writer-data.js').write_text('// Generated by scripts/generate-hebrew-writer.py. Noto Sans Hebrew: SIL OFL 1.1.\n// Authored print-letter practice paths, not a claim of universal handwriting order.\nexport const hebrewWriterData='+json.dumps(out,ensure_ascii=False,separators=(',',':'))+';\n')
